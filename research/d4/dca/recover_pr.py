#!/usr/bin/env python3
"""Recover the 32-band *perfect reconstruction* prototype that FFmpeg's DCA decoder uses.

Observation (STATUS.md): FFmpeg 9.0.2's FILTS = 1 output does not match the ETSI TS 102 114
Annex D.8 perfect-reconstruction table (relative deviations up to 3e-4 of the peak), while
FILTS = 0 matches Annex D.8 to float precision. This script measures FFmpeg's effective
prototype from impulse responses of the `pr_probe` stream (examples/synth.rs): one unit
subband impulse per band k at t = 0, mono, FILTS = 1. With the C.3.6 structure
  out[32 m + i] = g * h[32 m + i] * (m even ? V[i] - V[31-i] : -(V[i] + V[31-i])),
  V[n] = cos((2k+1)(2n+1) pi / 128),  g = x0 * QMF_GAIN / 2^23,
h is solved per coefficient by least squares over all 32 bands. No decoder source is read.
usage: recover_pr.py PROBE.dts.meta PROBE.ref.f32 SPEC_TABLES.rs OUT.rs
"""
import sys, re
import numpy as np
meta = dict(l.split('=', 1) for l in open(sys.argv[1]).read().split() if '=' in l)
ref = np.fromfile(sys.argv[2], dtype='<f4').astype(np.float64)
fs = int(meta['frame_samples']); first = int(meta['first']); ep = int(meta['episode'])
scale = {110: 1412538}[int(meta['scale7'])]   # Annex D.1.2
step = 79692 / 4194304.0                      # Annex D.2.1, ABITS 12
x0 = int(meta['q']) * step * scale
g = x0 * (0.25 * 128 * np.sqrt(2)) / 8388608.0
num = np.zeros(512); den = np.zeros(512)
n = np.arange(32)
for k in range(32):
    out = ref[(first + k * ep) * fs:(first + k * ep) * fs + 512]
    V = np.cos((2 * k + 1) * (2 * n + 1) * np.pi / 128)
    U = V - V[::-1]; W = -(V + V[::-1])
    G = np.concatenate([(U if m % 2 == 0 else W) for m in range(16)]) * g
    num += G * out; den += G * G
h = num / den
# self-check: resynthesize every probe response
worst = 0
for k in range(32):
    out = ref[(first + k * ep) * fs:(first + k * ep) * fs + 512]
    V = np.cos((2 * k + 1) * (2 * n + 1) * np.pi / 128)
    U = V - V[::-1]; W = -(V + V[::-1])
    G = np.concatenate([(U if m % 2 == 0 else W) for m in range(16)]) * g
    worst = max(worst, np.abs(G * h - out).max())
    tail = ref[(first + k * ep) * fs + 512:(first + k * ep + 1) * fs + 512]
    worst = max(worst, np.abs(tail).max())
assert worst < 2e-7, worst
s = open(sys.argv[3]).read()
a = s.index('pub static QMF_PERFECT'); b = s.index('];', a)
spec = np.array([float(v) for v in re.findall(r'-?\d\.\d+e[-+]\d+', s[a:b])])
assert len(spec) == 512
o = ['// @generated by research/d4/dca/recover_pr.py; do not edit by hand.',
     '//! FFmpeg-effective 32-band perfect-reconstruction prototype (sign-modified, C.3.6 layout).',
     '//! Black-box measured from FFmpeg 9.0.2 output; differs from ETSI TS 102 114 Annex D.8',
     '//! (max |delta| = %.3e, peak %.6e). Resynthesis error of the probe: %.2e.' % (np.abs(h - spec).max(), np.abs(spec).max(), worst),
     '//! Provenance needs owner review (research/d4/dca/STATUS.md).',
     'pub(crate) static QMF_PERFECT_REF: [f64; 512] = [']
for i in range(0, 512, 4):
    o.append('    ' + ', '.join('%.10e' % v for v in h[i:i + 4]) + ',')
o.append('];')
open(sys.argv[4], 'w').write('\n'.join(o) + '\n')
print('ok worst resynthesis %.2e, max delta vs spec %.3e' % (worst, np.abs(h - spec).max()))
