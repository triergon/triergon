/// The expected samples of a case, one row each:
/// `track ordinal description offset dts cts delta sync [payload];`, where `sync` marks a
/// sync sample and `-` a non-sync one.
macro_rules! samples {
    ($($track:literal $ordinal:literal $description:literal $offset:literal $dts:literal
       $cts:literal $delta:literal $sync:tt [$($byte:literal),*];)*) => {
        &[$(Expected {
            track: $track,
            ordinal: $ordinal,
            description: $description,
            offset: $offset,
            dts: $dts,
            cts: $cts,
            delta: $delta,
            sync: samples!(@sync $sync),
            payload: &[$($byte),*],
        }),*]
    };
    (@sync sync) => {
        true
    };
    (@sync -) => {
        false
    };
}
