/// The size a glyph is hinted at: the size's 16.16 scales from font units
/// to 26.6 pixels, which FreeType's auto-hinter takes unrounded (not the
/// integer-ppem scales of TrueType hinting), and its pixels per em.
#[derive(Clone, Copy, Debug)]
pub(crate) struct Scaler {
    pub(crate) x_scale: i64,
    pub(crate) y_scale: i64,
    pub(crate) ppem: u16,
}

/// The auto-hinter's state for one face. Storage is charged to the face's
/// budget.
#[derive(Debug)]
pub(crate) struct Autofit {
    budget: Budget,
    globals: OnceLock<Globals>,
    /// The storage the last load hinted with, for the next one. A load takes
    /// it out for as long as it hints and puts it back after, so concurrent
    /// loads of the face never share it: a load that finds none allocates
    /// its own.
    scratch: Mutex<Option<Scratch>>,
}

/// `AF_FaceGlobalsRec`, as the default load needs it.
#[derive(Debug)]
struct Globals {
    coverage: Coverage,
    /// FreeType's reverse charmap without HarfBuzz: each glyph the Unicode
    /// charmap maps a code point of the adjustment database to, with that
    /// code point, sorted by glyph and otherwise in database order. A later
    /// code point replaces an earlier one for the same glyph, so the last
    /// one of a glyph's run applies.
    reverse: BudgetVec<(u16, u32)>,
    /// Each latin and CJK style's metrics, once measured: `None` for a
    /// latin style without blue zones, which the dummy writing system then
    /// hints.
    metrics: BudgetVec<OnceLock<Option<Charged<Box<StyleMetrics>>>>>,
    /// `FT_IS_FIXED_WIDTH`: `post.isFixedPitch`.
    fixed_pitch: bool,
}

/// A style's metrics in font units, as its writing system measures them
/// (`AF_StyleMetricsRec` and the writing system's extension of it).
#[derive(Debug)]
#[expect(clippy::large_enum_variant, reason = "kept boxed, one per style")]
enum StyleMetrics {
    Latin(latin::Metrics),
    Cjk(cjk::Metrics),
}

/// What hints a glyph at a size.
#[derive(Debug)]
#[expect(clippy::large_enum_variant, reason = "one per load, on the stack")]
enum Hinter {
    Dummy,
    /// The style's metrics, scaled.
    Latin(latin::Metrics),
    /// The style's metrics, scaled.
    Cjk(cjk::Metrics),
    /// The Indic writing system, which hints with the CJK routines but is
    /// not ported.
    Indic,
}

impl Hinter {
    /// The 16.16 scales the writing system hints with: the scaler's, in the
    /// 32 bits of an `FT_Fixed`, as the CJK metrics keep them, or the latin
    /// metrics' with the vertical scale fitted to the x height.
    fn scales(&self, scaler: Scaler) -> (i64, i64) {
        match self {
            Self::Latin(metrics) => (metrics.x_scale(), metrics.y_scale()),
            Self::Cjk(metrics) => (metrics.x_scale(), metrics.y_scale()),
            Self::Dummy | Self::Indic => (wrap(scaler.x_scale), wrap(scaler.y_scale)),
        }
    }

    /// The style metrics' `digits_have_same_width`: false for the dummy
    /// writing system, whose metrics are zeroed, and here for the Indic one,
    /// whose glyphs, as CJK ones, advance by the rounded scaled advance
    /// whatever it says.
    fn digits_have_same_width(&self) -> bool {
        match self {
            Self::Latin(metrics) => metrics.digits_have_same_width(),
            Self::Cjk(metrics) => metrics.digits_have_same_width(),
            Self::Dummy | Self::Indic => false,
        }
    }
}

/// The face, as the auto-hinter's metrics are measured on it.
pub(super) struct Face<'f> {
    font: &'f Font,
    /// The face's Unicode charmap, as `FT_Select_Charmap` selects it.
    charmap: Option<Charmap<'f>>,
    /// Where scratch storage is charged.
    budget: &'f Budget,
}

impl Face<'_> {
    /// `FT_Get_Char_Index` through the Unicode charmap.
    fn glyph(&self, c: char) -> Option<GlyphId> {
        self.charmap?.glyph(u32::from(c))
    }

    /// `FT_Load_Glyph` with `FT_LOAD_NO_SCALE` into `outline`: whether the
    /// glyph loads. A glyph FreeType cannot load either is skipped by the
    /// callers; this crate's limits and budgets fail the load.
    fn load_units(
        &self,
        glyph: GlyphId,
        outline: &mut Outline,
        work: &mut WorkBudget,
    ) -> Result<bool> {
        match self.font.load(glyph, Scale::UNITS, outline, work) {
            Ok(_) => Ok(true),
            Err(Error::Invalid(_) | Error::Truncated | Error::Overflow) => Ok(false),
            Err(error) => Err(error),
        }
    }
}

/// The storage hinting one glyph needs besides the caller's outline.
#[derive(Debug)]
struct Scratch {
    hints: GlyphHints,
    /// The glyph in font units, for a load that returns only advances.
    outline: Outline,
}

impl Scratch {
    fn new(budget: &Budget) -> Self {
        Self {
            hints: GlyphHints::new(budget),
            outline: Outline::new(budget),
        }
    }
}

/// A glyph loaded at a size, and what hints it.
struct GlyphLoad<'a> {
    font: &'a Font,
    globals: &'a Globals,
    glyph: GlyphId,
    scaler: Scaler,
    hinter: Hinter,
}

impl Autofit {
    pub(crate) const fn new(budget: Budget) -> Self {
        Self {
            budget,
            globals: OnceLock::new(),
            scratch: Mutex::new(None),
        }
    }

    /// `af_face_globals_new`: the style coverage and the reverse charmap,
    /// computed once.
    fn globals(&self, font: &Font, work: &mut WorkBudget) -> Result<&Globals> {
        if let Some(globals) = self.globals.get() {
            return Ok(globals);
        }
        let charmap = font.unicode_charmap();
        let coverage = Coverage::new(charmap, font.glyph_count(), &self.budget, work)?;
        let mut reverse = BudgetVec::new(&self.budget);
        if let Some(charmap) = charmap {
            for &(code, _) in &ADJUSTMENTS {
                if let Some(glyph) = charmap.glyph(code) {
                    reverse.try_push((glyph.0, code)).map_err(|e| e.error)?;
                }
            }
            // Stable, so that a glyph's code points keep the database's order.
            reverse.sort_by_key(|&(glyph, _)| glyph);
        }
        let mut metrics = BudgetVec::new(&self.budget);
        metrics.try_extend_with(STYLES.len(), |_| OnceLock::new())?;
        let post = font.tables.post.map(|t| t.bytes(font.data.as_ref()));
        let globals = Globals {
            coverage,
            reverse,
            metrics,
            fixed_pitch: crate::metrics::fixed_pitch(post),
        };
        // Another thread may have been first; its globals are the same.
        Ok(self.globals.get_or_init(|| globals))
    }

    /// The writing system that hints `glyph` at `scaler` for `scope`
    /// (`af_face_globals_get_metrics` and the metrics' scaling), a latin or
    /// CJK style's metrics measured on the face once. A glyph outside the
    /// face is `Invalid`.
    ///
    /// For the advance alone a CJK or Indic glyph takes the dummy writing
    /// system, without measuring its style: none of the three hints
    /// advances (`AF_SCALER_FLAG_NO_ADVANCE`), and all three scale them by
    /// the scaler's scales.
    fn hinter(
        &self,
        globals: &Globals,
        font: &Font,
        glyph: GlyphId,
        scaler: Scaler,
        scope: Scope,
        work: &mut WorkBudget,
    ) -> Result<Hinter> {
        font.check(glyph)?;
        let style = globals.coverage.style(glyph.0);
        match STYLES[style].writing_system {
            WritingSystem::Dummy => return Ok(Hinter::Dummy),
            WritingSystem::Cjk | WritingSystem::Indic if scope == Scope::Advance => {
                return Ok(Hinter::Dummy);
            }
            WritingSystem::Indic => return Ok(Hinter::Indic),
            WritingSystem::Latin | WritingSystem::Cjk => {}
        }
        let cell = &globals.metrics[style];
        if cell.get().is_none() {
            let face = Face {
                font,
                charmap: font.unicode_charmap(),
                budget: &self.budget,
            };
            let measured = match STYLES[style].writing_system {
                WritingSystem::Cjk => {
                    Some(StyleMetrics::Cjk(cjk::Metrics::new(&face, style, work)?))
                }
                _ => latin::Metrics::new(&face, style, work)?.map(StyleMetrics::Latin),
            };
            let charged = measured
                .map(|m| Charged::boxed(&self.budget, m))
                .transpose()?;
            // A thread that measured first measured the same.
            let _ = cell.set(charged);
        }
        let metrics: Option<&StyleMetrics> = match cell.get() {
            Some(Some(metrics)) => Some(metrics),
            _ => None,
        };
        let (x_scale, y_scale) = (scaler.x_scale, scaler.y_scale);
        Ok(match metrics {
            Some(StyleMetrics::Latin(metrics)) => Hinter::Latin(metrics.scaled(x_scale, y_scale)),
            Some(StyleMetrics::Cjk(metrics)) => Hinter::Cjk(metrics.scaled(x_scale, y_scale)),
            None => Hinter::Dummy,
        })
    }

    /// The face's state and the writing system for loading `glyph` at
    /// `scaler` for `scope`.
    fn glyph_load<'a>(
        &'a self,
        font: &'a Font,
        glyph: GlyphId,
        scaler: Scaler,
        scope: Scope,
        work: &mut WorkBudget,
    ) -> Result<GlyphLoad<'a>> {
        let globals = self.globals(font, work)?;
        let hinter = self.hinter(globals, font, glyph, scaler, scope, work)?;
        Ok(GlyphLoad {
            font,
            globals,
            glyph,
            scaler,
            hinter,
        })
    }

    /// Runs `f` with the face's scratch storage, or with new storage while
    /// another load holds it, and keeps the storage for the next load.
    fn with_scratch<T>(&self, f: impl FnOnce(&mut Scratch) -> T) -> T {
        // A load that panicked left nothing half-written in the slot.
        let lock = || self.scratch.lock().unwrap_or_else(PoisonError::into_inner);
        let kept = lock().take();
        let mut scratch = kept.unwrap_or_else(|| Scratch::new(&self.budget));
        let result = f(&mut scratch);
        *lock() = Some(scratch);
        result
    }

    /// `af_loader_load_glyph` for `FT_LOAD_DEFAULT`: loads `glyph` into
    /// `outline` hinted at `scaler`, moved by the hinted left phantom
    /// point, and returns the glyph slot's metrics: the box of every point
    /// fitted outwards to whole pixels, and the advances of
    /// [`Self::advances`]. Hinted coordinates wrap in 32 bits.
    ///
    /// # Errors
    ///
    /// `Unsupported` for a glyph with points of an Indic style; those of
    /// loading the glyph in font units; `Policy` when `work` runs out; and
    /// the face budget's errors.
    pub(crate) fn load(
        &self,
        font: &Font,
        glyph: GlyphId,
        scaler: Scaler,
        outline: &mut Outline,
        work: &mut WorkBudget,
    ) -> Result<GlyphMetrics> {
        let load = self.glyph_load(font, glyph, scaler, Scope::Outline, work)?;
        let units = load.load_units(outline, work)?;
        let pp = self.with_scratch(|scratch| {
            load.hint(&mut scratch.hints, units, outline, Scope::Outline, work)
        })?;
        if pp.0 != 0 {
            // `FT_Outline_Translate`.
            let dx = to_i32(pp.0);
            for p in outline.points_mut() {
                p.point.x = p.point.x.wrapping_sub(dx);
            }
        }
        let (horizontal, vertical) = load.advances(units, pp);
        let [x_min, y_min, x_max, y_max] = control_box(outline).map(i64::from);
        let (left, bottom) = (pix_floor(x_min), pix_floor(y_min));
        let (right, top) = (pix_ceil(x_max), pix_ceil(y_max));
        Ok(GlyphMetrics {
            advance: to_i32(horizontal),
            vertical_advance: to_i32(vertical),
            // `FT_Load_Glyph` scales the linear advance after any load, as
            // the unhinted loads do.
            linear_vertical_advance: linear_advance(units.vertical_units, scaler.y_scale),
            bearing_x: to_i32(left),
            bearing_y: to_i32(top),
            width: to_i32(right - left),
            height: to_i32(top - bottom),
        })
    }

    /// The horizontal and vertical advances of [`Self::load`], rounded to
    /// whole pixels, found with as little of the load as they need: a glyph
    /// that the dummy, CJK or Indic writing systems hint advances by its
    /// scaled advance, read without its points, and a latin glyph needs
    /// only its vertical edges hinted.
    ///
    /// # Errors
    ///
    /// As [`Self::load`], but Indic glyphs give their advances.
    pub(crate) fn advances(
        &self,
        font: &Font,
        glyph: GlyphId,
        scaler: Scaler,
        work: &mut WorkBudget,
    ) -> Result<(i64, i64)> {
        let load = self.glyph_load(font, glyph, scaler, Scope::Advance, work)?;
        if !matches!(load.hinter, Hinter::Latin(_)) {
            let units = font.unscaled_advances(glyph, work)?;
            let pp2x = mul_fix(units.horizontal, scaler.x_scale);
            return Ok(load.advances(units, (0, pix_round(pp2x))));
        }
        self.with_scratch(|scratch| {
            let units = load.load_units(&mut scratch.outline, work)?;
            let pp = load.hint(
                &mut scratch.hints,
                units,
                &mut scratch.outline,
                Scope::Advance,
                work,
            )?;
            Ok(load.advances(units, pp))
        })
    }
}

impl GlyphLoad<'_> {
    /// `FT_Load_Glyph` with `FT_LOAD_NO_SCALE`, as the auto-hinter loads the
    /// glyph it hints: its outline in font units into `outline`, and its
    /// advances.
    fn load_units(&self, outline: &mut Outline, work: &mut WorkBudget) -> Result<Advances> {
        let units = self.font.load(self.glyph, Scale::UNITS, outline, work)?;
        Ok(Advances {
            horizontal: i64::from(units.advance),
            vertical: i64::from(units.vertical_advance),
            vertical_units: units.linear_vertical_advance,
        })
    }

    /// Hints the glyph loaded in font units into `outline` (for
    /// [`Scope::Outline`]) with `hints`, whose contents it replaces, and
    /// returns the hinted phantom points' x: the part of
    /// `af_loader_load_glyph` between loading and the metrics. `units` are
    /// the glyph's advances in font units.
    ///
    /// The right phantom point starts at the scaled advance. A glyph
    /// without points keeps both as they are. Otherwise, for a latin glyph
    /// with two or more hinted vertical edges, the side bearings follow the
    /// outermost edges' moves, rounded, with a pixel more where rounding
    /// would eat a side bearing; else, as the dummy and CJK writing systems
    /// leave advances unhinted (`AF_SCALER_FLAG_NO_ADVANCE`), both points
    /// are rounded.
    ///
    /// # Errors
    ///
    /// `Unsupported` for a glyph with points of an Indic style.
    fn hint(
        &self,
        hints: &mut GlyphHints,
        units: Advances,
        outline: &mut Outline,
        scope: Scope,
        work: &mut WorkBudget,
    ) -> Result<(i64, i64)> {
        let (x_scale, y_scale) = self.hinter.scales(self.scaler);
        let pp2x = mul_fix(units.horizontal, x_scale);
        if outline.is_empty() {
            return Ok((0, pp2x));
        }
        let metrics = match &self.hinter {
            Hinter::Latin(metrics) => metrics,
            Hinter::Cjk(metrics) => {
                hints.x_scale = x_scale;
                hints.y_scale = y_scale;
                hints.reload(outline, self.font.units_per_em(), work)?;
                cjk::apply(hints, metrics, work)?;
                hints.save(outline);
                return Ok((0, pix_round(pp2x)));
            }
            Hinter::Dummy => {
                // `af_dummy_hints_apply`: the points only scaled.
                if scope == Scope::Outline {
                    for p in outline.points_mut() {
                        p.point.x = to_i32(mul_fix(i64::from(p.point.x), x_scale));
                        p.point.y = to_i32(mul_fix(i64::from(p.point.y), y_scale));
                    }
                }
                return Ok((0, pix_round(pp2x)));
            }
            Hinter::Indic => return Err(Error::Unsupported("the Indic auto-hinter")),
        };
        hints.x_scale = x_scale;
        hints.y_scale = y_scale;
        hints.reload(outline, self.font.units_per_em(), work)?;
        let info = latin::Glyph {
            coverage: self.globals.coverage.entry(self.glyph.0),
            adjustment: self.globals.adjustment(self.glyph),
            ppem: self.scaler.ppem,
            italic: self.font.style().italic,
        };
        latin::apply(hints, metrics, info, scope, work)?;
        if scope == Scope::Outline {
            hints.save(outline);
        }
        let edges = hints.axis[0].edges.as_slice();
        let [first, .., last] = edges else {
            return Ok((0, pix_round(pp2x)));
        };
        let old_rsb = wrap(pp2x - last.opos);
        let old_lsb = first.opos;
        let new_lsb = first.pos;
        let mut pp1x_unhinted = new_lsb - old_lsb;
        let mut pp2x_unhinted = last.pos + old_rsb;
        // Prefer too much space to too little at very small sizes.
        if old_lsb < 24 {
            pp1x_unhinted -= 8;
        }
        if old_rsb < 24 {
            pp2x_unhinted += 8;
        }
        let mut pp1x = pix_round(pp1x_unhinted);
        let mut pp2x = pix_round(pp2x_unhinted);
        if pp1x >= new_lsb && old_lsb > 0 {
            pp1x = wrap(pp1x - 64);
        }
        if pp2x <= last.pos && old_rsb > 0 {
            pp2x = wrap(pp2x + 64);
        }
        Ok((pp1x, pp2x))
    }

    /// The advances `af_loader_load_glyph` reports, rounded to whole
    /// pixels, from the glyph's advances in font units `units` and its
    /// hinted phantom points `pp`: for a fixed-pitch face, or a digit of a
    /// style whose digits share one advance, the scaled advance; else the
    /// distance between the phantom points, an advance of zero staying
    /// zero; and the vertical advance scaled by the writing system's
    /// vertical scale.
    fn advances(&self, units: Advances, (pp1x, pp2x): (i64, i64)) -> (i64, i64) {
        let (x_scale, y_scale) = self.hinter.scales(self.scaler);
        let digits_same = self.hinter.digits_have_same_width();
        let digit = self.globals.coverage.entry(self.glyph.0) & DIGIT != 0;
        let horizontal = if self.globals.fixed_pitch || (digit && digits_same) {
            mul_fix(units.horizontal, x_scale)
        } else if units.horizontal != 0 {
            pp2x - pp1x
        } else {
            0
        };
        let vertical = mul_fix(units.vertical, y_scale);
        (pix_round(horizontal), pix_round(vertical))
    }
}

impl Globals {
    /// The adjustment database's flags for `glyph`, through the reverse
    /// charmap: those of the last code point listed for it.
    fn adjustment(&self, glyph: GlyphId) -> u16 {
        let entries = self.reverse.as_slice();
        let end = entries.partition_point(|&(g, _)| g <= glyph.0);
        match end.checked_sub(1).map(|last| entries[last]) {
            Some((g, code)) if g == glyph.0 => latin::adjustment(code),
            _ => 0,
        }
    }
}
