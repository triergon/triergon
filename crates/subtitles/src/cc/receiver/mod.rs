/// The receiver's ASS script header.
pub const ASS_HEADER: &str = "[Script Info]\n\
; Script generated by FFmpeg/Lavc63.1.100\n\
ScriptType: v4.00+\n\
PlayResX: 384\n\
PlayResY: 288\n\
ScaledBorderAndShadow: yes\n\
YCbCr Matrix: None\n\
\n\
[V4+ Styles]\n\
Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding\n\
Style: Default,Monospace,16,&Hffffff,&Hffffff,&H0,&H0,0,0,0,0,100,100,0,0,3,1,0,2,10,10,10,1\n\
\n\
[Events]\n\
Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text\n";

/// Which field's CEA-608 pairs the receiver decodes.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub enum DataField {
    /// The field of the first construct of the first packet.
    #[default]
    Auto,
    First,
    Second,
}

/// The receiver's options, as FFmpeg's `ccaption` decoder names them.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Options {
    /// `real_time`: report the screen as it changes.
    pub real_time: bool,
    /// `real_time_latency_msec`: the least time between two real-time reports of
    /// written characters, 0 to 500 ms.
    pub real_time_latency_ms: u16,
    /// `data_field`.
    pub data_field: DataField,
}

impl Default for Options {
    fn default() -> Self {
        Self {
            real_time: false,
            real_time_latency_ms: 200,
            data_field: DataField::Auto,
        }
    }
}

/// The events one packet produced: a presentation time, a display duration and
/// one ASS event line per rectangle.
#[derive(Debug)]
pub struct Subtitle {
    /// Microseconds; `None` when unknown.
    pub pts: Option<i64>,
    /// Display duration in milliseconds; `u32::MAX` (unknown) in real-time mode.
    pub end_ms: u32,
    lines: Text,
    ends: BudgetVec<usize>,
}

impl Subtitle {
    #[must_use]
    pub fn new(pool: &Budget) -> Self {
        Self {
            pts: None,
            end_ms: 0,
            lines: Text::new(pool),
            ends: BudgetVec::new(pool),
        }
    }

    /// The ASS event lines (`ReadOrder,Layer,Style,Name,MarginL,MarginR,MarginV,Effect,Text`).
    pub fn lines(&self) -> impl ExactSizeIterator<Item = &[u8]> {
        let text = self.lines.as_bytes();
        let ends = self.ends.as_slice();
        (0..ends.len()).map(move |i| {
            let start = if i == 0 { 0 } else { ends[i - 1] };
            &text[start..ends[i]]
        })
    }

    #[must_use]
    pub fn is_empty(&self) -> bool {
        self.ends.is_empty()
    }

    fn clear(&mut self, pts: Option<i64>) {
        self.pts = pts;
        self.end_ms = 0;
        self.lines.clear();
        self.ends.clear();
    }

    fn push(&mut self, read_order: u32, text: &[u8]) -> Result<()> {
        self.lines.put(itoa(read_order).as_slice())?;
        self.lines.put(b",0,Default,,0,0,0,,")?;
        self.lines.put(text)?;
        if self.ends.len() == self.ends.capacity() {
            self.ends.try_reserve_exact(self.ends.len().max(4))?;
        }
        self.ends
            .try_push(self.lines.len())
            .map_err(|rejected| rejected.error)
    }
}

/// Decimal digits of `value`, without allocation.
fn itoa(mut value: u32) -> Digits {
    let mut digits = Digits {
        bytes: [0; 10],
        start: 10,
    };
    loop {
        digits.start -= 1;
        digits.bytes[digits.start] = b'0' + (value % 10) as u8;
        value /= 10;
        if value == 0 {
            return digits;
        }
    }
}

struct Digits {
    bytes: [u8; 10],
    start: usize,
}

impl Digits {
    fn as_slice(&self) -> &[u8] {
        &self.bytes[self.start..]
    }
}

/// Two captured screens. Captures alternate between them in pop-on mode, so
/// the capture before the latest stays available.
#[derive(Debug)]
struct Snapshots {
    text: [Text; 2],
    current: usize,
    /// When the previous and the latest snapshot were reported, microseconds
    /// (`i64::MIN` when a packet time was unknown).
    times: [i64; 2],
}

impl Snapshots {
    fn current(&mut self) -> &mut Text {
        &mut self.text[self.current]
    }
}

/// When a packet is presented.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub struct Clock {
    /// Microseconds, `None` when unknown.
    pub pts: Option<i64>,
    /// The packet's duration in milliseconds (rounded as FFmpeg rescales it,
    /// kept to 32 bits); 0 when unknown. An event of no display time that the
    /// packet produces lasts this long, as FFmpeg's decode API sets it.
    pub duration_ms: u32,
}

/// FFmpeg's `ccaption` decoder.
#[derive(Debug)]
pub struct Decoder {
    options: Options,
    field: Option<u8>,
    memory: Memory,
    snapshots: Snapshots,
    /// The last control code, ignored when sent again (codes are sent twice).
    last_control: [u8; 2],
    /// Characters were written to the displayed screen since the last
    /// real-time report.
    touched: bool,
    last_real_time: i64,
    read_order: u32,
}

impl Decoder {
    #[must_use]
    pub fn new(pool: &Budget, options: Options) -> Self {
        Self {
            options,
            field: match options.data_field {
                DataField::Auto => None,
                DataField::First => Some(0),
                DataField::Second => Some(1),
            },
            memory: Memory::default(),
            snapshots: Snapshots {
                text: [Text::new(pool), Text::new(pool)],
                current: 0,
                times: [0; 2],
            },
            last_control: [0; 2],
            touched: false,
            last_real_time: 0,
            read_order: 0,
        }
    }

    /// The ASS script header events refer to.
    #[must_use]
    pub const fn header(&self) -> &'static str {
        ASS_HEADER
    }

    /// Decodes one packet of `cc_data` constructs into `out`. Returns whether
    /// `out` holds events.
    ///
    /// # Errors
    ///
    /// Only when the budget cannot hold the text.
    pub fn decode(&mut self, packet: &[u8], clock: Clock, out: &mut Subtitle) -> Result<bool> {
        out.clear(clock.pts);
        let now = clock.pts.unwrap_or(i64::MIN);
        for triplet in triplets(packet) {
            let field = triplet.flags & 1;
            let field = *self.field.get_or_insert(field);
            if !triplet.valid()
                || !matches!(triplet.kind(), CcType::Field1 | CcType::Field2)
                || triplet.flags & 1 != field
            {
                continue;
            }
            // A second byte failing parity drops the pair; a first byte failing
            // it becomes the solid block.
            let [hi, lo] = triplet.data;
            if !odd_parity(lo) {
                continue;
            }
            let hi = if odd_parity(hi) { hi & 0x7f } else { 0x7f };
            // Padding is a null pair under a standard flag byte; under another
            // flag byte a null pair counts as a code.
            if matches!(triplet.flags, 0xfa | 0xfc | 0xfd) && hi == 0 && lo & 0x7f == 0 {
                continue;
            }
            self.pair(hi, lo & 0x7f, now, out)?;
        }
        // The interval runs from the subtitle's time, which an erase or end of
        // caption in this packet has moved back to its snapshot's start.
        let at = out.pts.unwrap_or(i64::MIN);
        if self.options.real_time
            && self.touched
            && at
                >= self
                    .last_real_time
                    .saturating_add(i64::from(self.options.real_time_latency_ms) * 1000)
        {
            self.last_real_time = at;
            self.touched = false;
            self.memory.capture(self.snapshots.current())?;
            let text = &self.snapshots.text[self.snapshots.current];
            out.push(self.read_order, text.as_bytes())?;
            self.read_order = self.read_order.wrapping_add(1);
            out.end_ms = u32::MAX;
        }
        if out.is_empty() {
            return Ok(false);
        }
        if out.end_ms == 0 {
            out.end_ms = clock.duration_ms;
        }
        Ok(true)
    }

    /// The drain after the last packet: reports the pop-on caption still
    /// waiting, once. Returns whether `out` holds an event.
    ///
    /// # Errors
    ///
    /// Only when the budget cannot hold the text.
    pub fn drain(&mut self, out: &mut Subtitle) -> Result<bool> {
        out.clear(None);
        let waiting = 1 - self.snapshots.current;
        if self.options.real_time || self.snapshots.text[waiting].is_empty() {
            return Ok(false);
        }
        out.push(self.read_order, self.snapshots.text[waiting].as_bytes())?;
        self.read_order = self.read_order.wrapping_add(1);
        self.snapshots.text[waiting].clear();
        let [start, end] = self.snapshots.times;
        out.pts = known(end);
        out.end_ms = milliseconds(end.wrapping_sub(start));
        Ok(true)
    }

    fn pair(&mut self, hi: u8, lo: u8, now: i64, out: &mut Subtitle) -> Result<()> {
        if hi < 0x20 {
            if [hi, lo] == self.last_control {
                return Ok(());
            }
            self.last_control = [hi, lo];
        } else {
            self.last_control = [0; 2];
        }
        let real_time = self.options.real_time;
        match self
            .memory
            .apply(hi, lo, real_time, self.snapshots.current())?
        {
            Effect::None => return Ok(()),
            Effect::Touched => {
                self.touched = true;
                return Ok(());
            }
            // A reported snapshot shows what was written so far.
            Effect::Snapshot => self.touched = false,
        }
        let pop_on = !real_time && self.memory.is_pop_on();
        if pop_on {
            self.snapshots.current ^= 1;
        }
        let snapshots = &mut self.snapshots;
        snapshots.times = [snapshots.times[1], now];
        let text = &snapshots.text[snapshots.current];
        if text.is_empty() && !real_time {
            return Ok(());
        }
        let [start, end] = snapshots.times;
        out.pts = known(start);
        out.end_ms = if real_time {
            // The next real-time report of written characters waits from here.
            self.last_real_time = start;
            u32::MAX
        } else {
            milliseconds(end.wrapping_sub(start))
        };
        out.push(self.read_order, text.as_bytes())?;
        self.read_order = self.read_order.wrapping_add(1);
        Ok(())
    }
}

fn known(time: i64) -> Option<i64> {
    (time != i64::MIN).then_some(time)
}

/// Microseconds to milliseconds, rounded to nearest with ties away from zero,
/// kept to 32 bits as FFmpeg's display time is.
fn milliseconds(us: i64) -> u32 {
    let ms = if us >= 0 {
        (i128::from(us) + 500) / 1000
    } else {
        (i128::from(us) - 500) / 1000
    };
    ms as u32
}
