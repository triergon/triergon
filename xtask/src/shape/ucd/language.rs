//! The OpenType language system tags HarfBuzz 14.6.0 maps BCP 47 languages to,
//! read from the tables `gen-tag-table.py` generated into its
//! `src/hb-ot-tag-table.hh`: the two- and three-letter primary languages, the
//! three-letter languages with several tags, the three-letter languages that
//! must not be taken for the OpenType tag spelt the same, and the rules of
//! `hb_ot_tags_from_complex_language` for languages that need more than their
//! first subtag.
//!
//! The header is C, but generated and regular; every line of the parts read is
//! recognised or the generation fails, so a different HarfBuzz layout cannot be
//! misread.

use std::path::Path;

use super::emit::Writer;
use super::{FILE_LIMIT, Generated};
use crate::shape::reference::{CACHE, HARFBUZZ};
use crate::{fetch, sha256};

/// The header in HarfBuzz 14.6.0's tree and its hash.
const TABLE: (&str, &str) = (
    "src/hb-ot-tag-table.hh",
    "19dd8ad0e75c6d0eaef0c9ccd0ba23d213ac4592ea702322f3afcff1e010e9b1",
);

/// The header's text, verified against its pinned hash.
pub fn load(root: &Path) -> Result<String, String> {
    let path = root.join(CACHE).join(HARFBUZZ.directory).join(TABLE.0);
    if !path.exists() {
        return Err(format!(
            "{}: missing; `cargo xtask shape prepare` unpacks the HarfBuzz release",
            path.display()
        ));
    }
    let data = fetch::read_bounded(&path, FILE_LIMIT)?;
    if sha256::hex(&data) != TABLE.1 {
        return Err(format!("{}: differs from HarfBuzz 14.6.0", path.display()));
    }
    String::from_utf8(data).map_err(|_| format!("{}: not UTF-8", path.display()))
}

pub fn generate(header: &str) -> Result<Generated, String> {
    let mut w = Writer::new(&format!(
        "// @generated by `cargo xtask shape ucd`; do not edit.\n\
         // The OpenType language system tags of BCP 47 languages, from {}\n\
         //     sha256 {}:\n\
         //   {}\n\
         //     sha256 {}\n",
        HARFBUZZ.url, HARFBUZZ.sha256, TABLE.0, TABLE.1
    ));
    w.raw("\nuse super::Pattern;\nuse crate::Tag;\n");

    let pairs = |name: &str| -> Result<Vec<String>, String> {
        let mut items = Vec::new();
        for line in body(header, &format!("static const LangTag {name}[] = {{"))? {
            let [language, tag] = <[[u8; 4]; 2]>::try_from(tags(line)?)
                .map_err(|_| format!("{name}: not a language and a tag: {line}"))?;
            items.push(format!("({}, {})", tag_expr(language), tag_expr(tag)));
        }
        sorted(name, &items)?;
        Ok(items)
    };
    let two = pairs("ot_languages2")?;
    w.array(
        "`ot_languages2`: each two-letter language, as a tag padded with spaces, and its \
         tags,\nsorted by language; a language with several tags lists them in order of \
         preference.",
        "LANGUAGES_2",
        "(Tag, Tag)",
        &two,
        8,
    );
    let three = pairs("ot_languages3")?;
    w.array(
        "`ot_languages3`: the three-letter languages with one tag, sorted.",
        "LANGUAGES_3",
        "(Tag, Tag)",
        &three,
        8,
    );

    let values: Vec<[u8; 4]> = body(
        header,
        "static const hb_tag_t ot_languages3_multi_values[] = {",
    )?
    .iter()
    .map(|line| one_tag(line))
    .collect::<Result<_, _>>()?;
    let mut multi = Vec::new();
    for line in body(
        header,
        "static const LangTagRange ot_languages3_multi[] = {",
    )? {
        let language = one_tag(line)?;
        let numbers: Vec<usize> = strip_comment(line)
            .rsplit(')')
            .next()
            .unwrap_or_default()
            .split(|c: char| !c.is_ascii_digit())
            .filter(|n| !n.is_empty())
            .map(|n| {
                n.parse()
                    .map_err(|_| format!("ot_languages3_multi: {line}"))
            })
            .collect::<Result<_, _>>()?;
        let [offset, count] = <[usize; 2]>::try_from(numbers)
            .map_err(|_| format!("ot_languages3_multi: no offset and count: {line}"))?;
        let tags = values
            .get(offset..offset + count)
            .ok_or_else(|| format!("ot_languages3_multi: range outside the values: {line}"))?;
        multi.push(format!("({}, &[{}])", tag_expr(language), tag_list(tags)));
    }
    sorted("ot_languages3_multi", &multi)?;
    w.array(
        "`ot_languages3_multi`: the three-letter languages with several tags, sorted, \
         with their\ntags in order of preference.",
        "LANGUAGES_3_MULTI",
        "(Tag, &[Tag])",
        &multi,
        24,
    );
    w.add_data(4 * values.len());

    let blocked: Vec<String> = body(header, "static const hb_tag_t ot_languages3_blocked[] = {")?
        .iter()
        .map(|line| one_tag(line).map(tag_expr))
        .collect::<Result<_, _>>()?;
    sorted("ot_languages3_blocked", &blocked)?;
    w.array(
        "`ot_languages3_blocked`: three-letter languages that select no language system, \
         although\nan OpenType tag is spelt as they are, sorted.",
        "LANGUAGES_3_BLOCKED",
        "Tag",
        &blocked,
        4,
    );

    let rules = complex(header)?;
    w.array(
        "The rules of `hb_ot_tags_from_complex_language`, in order: a language that \
         matches a rule\nselects its tags in order of preference.",
        "COMPLEX",
        "(Pattern, &[Tag])",
        &rules,
        56,
    );
    Ok(w.finish())
}

/// The lines of the array whose declaration is `opening`, up to its `};`.
fn body<'h>(header: &'h str, opening: &str) -> Result<Vec<&'h str>, String> {
    let mut lines = header.lines().skip_while(|line| *line != opening);
    if lines.next().is_none() {
        return Err(format!("hb-ot-tag-table.hh: no `{opening}`"));
    }
    let mut body = Vec::new();
    for line in lines {
        if line == "};" {
            return Ok(body);
        }
        body.push(line);
    }
    Err(format!("hb-ot-tag-table.hh: `{opening}` does not end"))
}

/// `line` without its `/* ... */` comments.
fn strip_comment(line: &str) -> String {
    let mut out = String::new();
    let mut rest = line;
    while let Some(start) = rest.find("/*") {
        out.push_str(&rest[..start]);
        rest = rest[start..]
            .split_once("*/")
            .map_or("", |(_, after)| after);
    }
    out.push_str(rest);
    out
}

/// Every `HB_TAG('a','b','c','d')` of `line` outside comments.
fn tags(line: &str) -> Result<Vec<[u8; 4]>, String> {
    let code = strip_comment(line);
    let mut found = Vec::new();
    for part in code.split("HB_TAG(").skip(1) {
        let letters = part.split(')').next().unwrap_or_default();
        let bytes: Vec<u8> = letters
            .split(',')
            .map(|letter| match letter.as_bytes() {
                [b'\'', c, b'\''] if c.is_ascii_graphic() || *c == b' ' => Ok(*c),
                _ => Err(format!("unexpected tag letter `{letter}` in: {line}")),
            })
            .collect::<Result<_, _>>()?;
        found.push(<[u8; 4]>::try_from(bytes).map_err(|_| format!("not four letters: {line}"))?);
    }
    Ok(found)
}

/// The only tag of `line`.
fn one_tag(line: &str) -> Result<[u8; 4], String> {
    match tags(line)?.as_slice() {
        [tag] => Ok(*tag),
        _ => Err(format!("not one tag: {line}")),
    }
}

fn tag_expr(tag: [u8; 4]) -> String {
    format!("Tag::new(b\"{}\")", String::from_utf8_lossy(&tag))
}

fn tag_list(tags: &[[u8; 4]]) -> String {
    tags.iter()
        .map(|&tag| tag_expr(tag))
        .collect::<Vec<_>>()
        .join(", ")
}

/// Fails unless the generated keys ascend, as HarfBuzz's binary searches need;
/// equal keys may repeat.
fn sorted(name: &str, items: &[String]) -> Result<(), String> {
    let key = |item: &String| -> String { item.split(')').next().unwrap_or_default().to_owned() };
    if items.windows(2).all(|w| key(&w[0]) <= key(&w[1])) {
        Ok(())
    } else {
        Err(format!("{name}: not sorted"))
    }
}

/// The C string literal in `text` and the length passed after it.
fn literal(text: &str) -> Result<(String, Option<usize>), String> {
    let (_, rest) = text
        .split_once('"')
        .ok_or_else(|| format!("no string in: {text}"))?;
    let (string, after) = rest
        .split_once('"')
        .ok_or_else(|| format!("unterminated string in: {text}"))?;
    if !string
        .bytes()
        .all(|b| b.is_ascii_alphanumeric() || b == b'-')
    {
        return Err(format!("unexpected string in: {text}"));
    }
    let length = after
        .trim_start_matches(", ")
        .split(')')
        .next()
        .and_then(|n| n.parse().ok());
    Ok((string.to_owned(), length))
}

/// A string and the length passed with it, which must be the string's.
fn counted(text: &str) -> Result<String, String> {
    match literal(text)? {
        (string, Some(length)) if length == string.len() => Ok(string),
        _ => Err(format!("length does not match the string: {text}")),
    }
}

/// The rules of `hb_ot_tags_from_complex_language` as `(Pattern, &[Tag])`
/// items, in the order the function tries them: the variant subtags first,
/// then the rules of the language's first letter.
fn complex(header: &str) -> Result<Vec<String>, String> {
    const PREAMBLE: [&str; 3] = [
        "if (limit - lang_str >= 7)",
        "const char *p = strchr (lang_str, '-');",
        "if (!p || p >= limit || limit - p < 5) goto out;",
    ];
    let mut lines = header
        .lines()
        .skip_while(|line| *line != "hb_ot_tags_from_complex_language (const char   *lang_str,")
        .skip(4)
        .map(|line| strip_comment(line).trim().to_owned())
        .filter(|line| !line.is_empty());
    if lines.next().as_deref() != Some("{") {
        return Err("hb_ot_tags_from_complex_language: not found".into());
    }
    let mut rules = Vec::new();
    let mut pattern: Option<String> = None;
    let mut letter: Option<char> = None;
    let mut tags: Vec<[u8; 4]> = Vec::new();
    let mut preamble = 0;
    let mut pending_prefix: Option<String> = None;
    for line in lines.by_ref() {
        let line = line.as_str();
        if preamble < PREAMBLE.len() {
            if line == "{" {
                continue;
            }
            if line != PREAMBLE[preamble] {
                return Err(format!(
                    "hb_ot_tags_from_complex_language: unexpected `{line}`"
                ));
            }
            preamble += 1;
            continue;
        }
        if let Some(rest) = line.strip_prefix("if (subtag_matches (p, limit, ") {
            pattern = Some(format!("Pattern::Subtag(\"{}\")", counted(rest)?));
        } else if let Some(rest) = line.strip_prefix("if (lang_matches (&lang_str[1], limit, ") {
            let c = letter.ok_or("lang_matches outside a case")?;
            pattern = Some(format!("Pattern::Prefix(b'{c}', \"{}\")", counted(rest)?));
        } else if let Some(rest) = line.strip_prefix("if (0 == strcmp (&lang_str[1], ") {
            let c = letter.ok_or("strcmp outside a case")?;
            let (string, _) = literal(rest)?;
            pattern = Some(format!("Pattern::Exact(b'{c}', \"{string}\")"));
        } else if let Some(rest) = line.strip_prefix("if (0 == strncmp (&lang_str[1], ") {
            pending_prefix = Some(counted(rest)?);
        } else if let Some(rest) = line.strip_prefix("&& subtag_matches (lang_str, limit, ") {
            let c = letter.ok_or("subtag_matches outside a case")?;
            let prefix = pending_prefix
                .take()
                .ok_or("subtag_matches without a prefix")?;
            pattern = Some(format!(
                "Pattern::PrefixSubtag(b'{c}', \"{prefix}\", \"{}\")",
                counted(rest)?
            ));
        } else if let Some(rest) = line.strip_prefix("case '") {
            letter = rest.chars().next().filter(char::is_ascii_lowercase);
            if letter.is_none() || !rest.ends_with("':") {
                return Err(format!("unexpected case: {line}"));
            }
        } else if line.starts_with("tags[0] = HB_TAG(")
            || (line.starts_with("HB_TAG(") && line.ends_with(','))
        {
            tags.push(one_tag(line)?);
        } else if let Some(rest) = line.strip_prefix("for (i = 0; i < ") {
            let n: usize = rest
                .split(' ')
                .next()
                .and_then(|n| n.parse().ok())
                .ok_or_else(|| format!("unexpected loop: {line}"))?;
            if n != tags.len() {
                return Err(format!("{n} possible tags, {} listed", tags.len()));
            }
        } else if line == "*count = 1;" {
            if tags.len() != 1 {
                return Err(format!("one tag counted, {} listed", tags.len()));
            }
        } else if line == "return true;" {
            let p = pattern.take().ok_or("a rule without a pattern")?;
            if tags.is_empty() {
                return Err(format!("{p}: no tags"));
            }
            rules.push(format!("({p}, &[{}])", tag_list(&tags)));
            tags.clear();
        } else if line == "return false;" {
            break;
        } else if !matches!(
            line,
            "{" | "}"
                | "};"
                | "break;"
                | "out:"
                | "switch (lang_str[0])"
                | "unsigned int i;"
                | "hb_tag_t possible_tags[] = {"
                | "tags[i] = possible_tags[i];"
                | "*count = i;"
        ) {
            return Err(format!(
                "hb_ot_tags_from_complex_language: unexpected `{line}`"
            ));
        }
    }
    if pattern.is_some() || !tags.is_empty() || pending_prefix.is_some() {
        return Err("hb_ot_tags_from_complex_language: an unfinished rule".into());
    }
    Ok(rules)
}

