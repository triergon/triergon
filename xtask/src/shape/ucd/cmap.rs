//! The code-point remappings of HarfBuzz 14.6.0's `cmap` accelerator:
//! `unicode_to_macroman` from `src/hb-ot-cmap-table.hh`, and the Arabic
//! private-use maps `gen-arabic-pua.py` generated into
//! `src/hb-ot-shaper-arabic-pua.hh`.
//!
//! Each array is found by its declaration and its length checked, and the two
//! Arabic map functions must read exactly as `crates/shape/src/cmap` ports
//! them, so a different HarfBuzz cannot be misread.

use std::path::Path;

use super::emit::Writer;
use super::{FILE_LIMIT, Generated};
use crate::shape::reference::{CACHE, HARFBUZZ};
use crate::{fetch, sha256};

/// The headers in HarfBuzz 14.6.0's tree and their hashes.
const CMAP: (&str, &str) = (
    "src/hb-ot-cmap-table.hh",
    "be710b7b24c85e106c457dd926bba776cc820c091eafe2e82f3fd92e097e3ec9",
);
const ARABIC_PUA: (&str, &str) = (
    "src/hb-ot-shaper-arabic-pua.hh",
    "09dbda72b045984b9a432949c2d20b92b8c3747cf24ea88c34ada744450f6d1c",
);

/// The two map functions, as the port reads them.
const MAPS: [&str; 2] = [
    "  return u<65277u ? (uint16_t)(_hb_arabic_pua_u16[((_hb_arabic_pua_u8[31u+((_hb_arabic_pua_b4(_hb_arabic_pua_u8,((((13835058055282164225ULL>>((((((((u)>>3))>>4))>>4))<<1))&3))<<4)+((((((u)>>3))>>4))&15)))<<4)+((((u)>>3))&15)])<<3)+((u)&7)]) : 0;",
    "  return u<65277u ? (uint16_t)(_hb_arabic_pua_u16[317u+((_hb_arabic_pua_u8[197u+((_hb_arabic_pua_b4(_hb_arabic_pua_u8+159u,((_hb_arabic_pua_b4(_hb_arabic_pua_u8+127u,((((((u)>>2))>>4))>>4)))<<4)+((((((u)>>2))>>4))&15)))<<4)+((((u)>>2))&15)])<<2)+((u)&3)]) : 0;",
];

/// Both headers' text, verified against their pinned hashes.
pub fn load(root: &Path) -> Result<[String; 2], String> {
    let read = |(name, hash): (&str, &str)| {
        let path = root.join(CACHE).join(HARFBUZZ.directory).join(name);
        if !path.exists() {
            return Err(format!(
                "{}: missing; `cargo xtask shape prepare` unpacks the HarfBuzz release",
                path.display()
            ));
        }
        let data = fetch::read_bounded(&path, FILE_LIMIT)?;
        if sha256::hex(&data) != hash {
            return Err(format!("{}: differs from HarfBuzz 14.6.0", path.display()));
        }
        String::from_utf8(data).map_err(|_| format!("{}: not UTF-8", path.display()))
    };
    Ok([read(CMAP)?, read(ARABIC_PUA)?])
}

pub fn generate([cmap, pua]: &[String; 2]) -> Result<Generated, String> {
    let mut w = Writer::new(&format!(
        "// @generated by `cargo xtask shape ucd`; do not edit.\n\
         // HarfBuzz's cmap code-point remappings, from {}\n\
         //     sha256 {}:\n\
         //   {}\n\
         //     sha256 {}\n\
         //   {}\n\
         //     sha256 {}\n",
        HARFBUZZ.url, HARFBUZZ.sha256, CMAP.0, CMAP.1, ARABIC_PUA.0, ARABIC_PUA.1
    ));
    let mac = macroman(cmap)?;
    w.array(
        "`unicode_to_macroman`: each code point and its Macintosh Roman code, sorted.",
        "MACROMAN",
        "(u16, u8)",
        &mac,
        4,
    );
    for line in MAPS {
        if !pua.lines().any(|l| l == line) {
            return Err(format!("{}: an Arabic map reads differently", ARABIC_PUA.0));
        }
    }
    let u8s = numbers(pua, "static const uint8_t _hb_arabic_pua_u8[453]=", 453)?;
    w.array(
        "`_hb_arabic_pua_u8`: the byte stages of the packed Arabic maps.",
        "ARABIC_PUA_U8",
        "u8",
        &u8s,
        1,
    );
    let u16s = numbers(pua, "static const uint16_t _hb_arabic_pua_u16[713]=", 713)?;
    w.array(
        "`_hb_arabic_pua_u16`: the code points of the packed Arabic maps.",
        "ARABIC_PUA_U16",
        "u16",
        &u16s,
        2,
    );
    Ok(w.finish())
}

/// The `{ 0xUUUU, 0xMM },` lines of `unicode_to_macroman`'s mapping.
fn macroman(header: &str) -> Result<Vec<String>, String> {
    let lines = block(header, "  mapping[] =")?;
    let mut items = Vec::new();
    let mut last = None;
    for line in lines {
        let inner = line
            .trim()
            .strip_prefix("{ 0x")
            .and_then(|l| l.strip_suffix(" },"))
            .ok_or(format!("unicode_to_macroman: unread line: {line}"))?;
        let (unicode, mac) = inner
            .split_once(", 0x")
            .ok_or(format!("unicode_to_macroman: unread line: {line}"))?;
        let unicode = u16::from_str_radix(unicode, 16).map_err(|e| format!("{line}: {e}"))?;
        let mac = u8::from_str_radix(mac, 16).map_err(|e| format!("{line}: {e}"))?;
        if last.is_some_and(|l| l >= unicode) {
            return Err(format!("unicode_to_macroman: not sorted at {line}"));
        }
        last = Some(unicode);
        items.push(format!("(0x{unicode:04X}, 0x{mac:02X})"));
    }
    Ok(items)
}

/// The lines between `opening` and the next `{` line's closing `};`.
fn block<'h>(header: &'h str, opening: &str) -> Result<Vec<&'h str>, String> {
    let mut lines = header.lines().skip_while(|l| *l != opening);
    if lines.next().is_none() || lines.next().map(str::trim) != Some("{") {
        return Err(format!("{opening}: not found"));
    }
    let body: Vec<&str> = lines.take_while(|l| l.trim() != "};").collect();
    Ok(body)
}

/// The comma-separated numbers of the array declared by `opening`, which must
/// hold `count`.
fn numbers(header: &str, opening: &str, count: usize) -> Result<Vec<String>, String> {
    let mut values = Vec::new();
    for line in block(header, opening)? {
        for value in line.split(',').map(str::trim).filter(|v| !v.is_empty()) {
            let n: u32 = value
                .parse()
                .map_err(|_| format!("{opening}: unread value {value}"))?;
            values.push(n.to_string());
        }
    }
    if values.len() != count {
        return Err(format!("{opening}: {} values", values.len()));
    }
    Ok(values)
}
