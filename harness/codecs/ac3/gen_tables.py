#!/usr/bin/env python3
"""Transcribe the numeric tables of ATSC A/52:2018 into Rust source.

Input: the text rendering of the A/52:2018 PDF produced by
`pdftotext -layout A52-2018.pdf a52.txt` (poppler).  Output: Rust source on stdout.
Every table is parsed from the spec text (never from another implementation) and
checked for its expected size.  Run:
  python3 -I harness/codecs/ac3/gen_tables.py target/agent-ac3/spec/a52.txt \
      > crates/codec-ac3/src/spec_tables.rs
"""
import re
import sys

text = open(sys.argv[1], encoding="utf-8").read().splitlines()


def find(title, start=0):
    for i in range(start, len(text)):
        if text[i].strip().startswith(title):
            return i
    raise SystemExit("table not found: " + title)


def grid(title, nvals, hexvals):
    """Tables laid out as rows 'A=n v0 .. v9' (addr = 10*A + B)."""
    i = find(title, 1000)
    vals = []
    while len(vals) < nvals:
        i += 1
        m = re.match(r"^\s*A=(\d+)\s+(.*)$", text[i])
        if not m:
            continue
        a = int(m.group(1))
        assert a * 10 == len(vals), (title, a, len(vals))
        for tok in m.group(2).split():
            vals.append(int(tok, 16) if hexvals else int(tok))
    assert len(vals) == nvals, (title, len(vals))
    return vals


def two_col(title, nrows, ncols_per_half, start=1000):
    """Tables laid out as 'idx v.. idx v..' with two halves per line."""
    i = find(title, start)
    out = {}
    while len(out) < nrows:
        i += 1
        toks = text[i].split()
        if not toks or not re.match(r"^\d+$", toks[0]):
            continue
        per = 1 + ncols_per_half
        if len(toks) % per != 0:
            continue
        for h in range(len(toks) // per):
            row = toks[h * per:(h + 1) * per]
            out[int(row[0])] = [int(t, 0) for t in row[1:]]
    assert sorted(out) == list(range(nrows)), (title, sorted(out))
    return [out[k] for k in range(nrows)]


def vq(n, entries):
    i = find("Table E4.%d VQ Table" % n, 11000)
    rows = {}
    while len(rows) < entries:
        i += 1
        m = re.match(r"^\s*(\d+)\s+((?:0x[0-9a-f]{4}\s*){6})$", text[i])
        if not m:
            continue
        idx = int(m.group(1))
        vals = [int(t, 16) for t in m.group(2).split()]
        vals = [v - 65536 if v >= 32768 else v for v in vals]
        assert idx not in rows
        rows[idx] = vals
    assert sorted(rows) == list(range(entries)), n
    return [rows[k] for k in range(entries)]


def emit_u(name, ty, vals, src, per=16):
    print("/// %s" % src)
    print("pub(crate) const %s: [%s; %d] = [" % (name, ty, len(vals)))
    for k in range(0, len(vals), per):
        print("    " + ", ".join(str(v) for v in vals[k:k + per]) + ",")
    print("];\n")


print("// @generated by harness/codecs/ac3/gen_tables.py from the text of ATSC A/52:2018.")
print("// Do not edit by hand; regenerate from the specification text instead.\n")

masktab = grid("Table 7.13 Bin Number to Band Number Table", 256, False)
emit_u("MASKTAB", "u8", masktab, "ATSC A/52:2018 Table 7.13 masktab[bin] (bins 253..255 are 0 in the spec).")
latab = grid("Table 7.14 Log-Addition Table", 256, True)
emit_u("LATAB", "u16", latab, "ATSC A/52:2018 Table 7.14 latab[val].")

hth_rows = two_col("Table 7.15 Hearing Threshold Table", 50, 3)
for f in range(3):
    emit_u("HTH_%d" % f, "u16", [r[f] for r in hth_rows],
           "ATSC A/52:2018 Table 7.15 hth[%d][band] (fscod %d)." % (f, f))

bap = two_col("Table 7.16 Bit Allocation Pointer Table", 64, 1)
emit_u("BAPTAB", "u8", [r[0] for r in bap], "ATSC A/52:2018 Table 7.16 baptab[address].")

bnd = two_col("Table 7.12 Banding Structure Tables", 50, 2)
emit_u("BNDTAB", "u8", [r[0] for r in bnd], "ATSC A/52:2018 Table 7.12 bndtab[band].")
emit_u("BNDSZ", "u8", [r[1] for r in bnd], "ATSC A/52:2018 Table 7.12 bndsz[band].")

hebap = two_col("Table E3.1 High Efficiency Bit Allocation Pointers", 64, 1, 9000)
emit_u("HEBAPTAB", "u8", [r[0] for r in hebap], "ATSC A/52:2018 Annex E Table E3.1 hebaptab[address].")

window = grid("Table 7.33 Transform Window Sequence", 256, False) if False else None

sizes = {1: 4, 2: 8, 3: 16, 4: 32, 5: 128, 6: 256, 7: 512}
for n, e in sizes.items():
    rows = vq(n, e)
    print("/// ATSC A/52:2018 Annex E Table E4.%d VQ table for hebap %d (16-bit two's complement)." % (n, n))
    print("pub(crate) const VQ_HEBAP%d: [[i16; 6]; %d] = [" % (n, e))
    for r in rows:
        print("    [" + ", ".join(str(v) for v in r) + "],")
    print("];\n")
