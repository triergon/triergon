#!/usr/bin/env python3
"""Emit crates/codec-dca/src/vq.rs from the codebooks recovered by recover_vq.py.
usage: gen_vq.py ADPCM.txt HFVQ.txt OUT.rs"""
import sys
def load(p):
    rows = [list(map(int, l.split())) for l in open(p) if l.strip() and not l.startswith('#')]
    return rows, open(p).readline().strip()
ad, adh = load(sys.argv[1])
hf, hfh = load(sys.argv[2])
assert len(ad) == 4096 and all(len(r) == 4 for r in ad)
assert len(hf) == 1024 and all(len(r) == 32 for r in hf)
o = []
o.append('// @generated by harness/codecs/dca/gen_vq.py; do not edit by hand.')
o.append('//! VQ codebooks of ETSI TS 102 114 Annex D.10.')
o.append('//!')
o.append('//! The specification defines both codebooks as normative but does not print them')
o.append('//! ("Due to its extensive size, this table is not included here", V1.2.1..V1.6.1).')
o.append('//! These values were recovered black-box from the observed output of the FFmpeg 9.0.2')
o.append('//! binary on synthetic probe streams (harness/codecs/dca/recover_vq.py); no decoder source')
o.append('//! was read. Recovery chain and provenance: harness/codecs/dca/STATUS.md.')
o.append('//! ' + adh.lstrip('# '))
o.append('//! ' + hfh.lstrip('# '))
o.append('')
o.append('/// D.10.1 ADPCM coefficient codebook: 4 096 vectors of 4 elements, each element x 2^13.')
o.append('pub static ADPCM_VQ: [[i16; 4]; 4096] = [')
for i in range(0, 4096, 4):
    o.append('    ' + ' '.join('[%s],' % ', '.join(map(str, r)) for r in ad[i:i + 4]))
o.append('];')
o.append('/// D.10.2 high-frequency subband codebook: 1 024 vectors of 32 elements, each element x 2^4.')
o.append('pub static HF_VQ: [[i8; 32]; 1024] = [')
for r in hf:
    o.append('    [%s],' % ', '.join(map(str, r)))
o.append('];')
open(sys.argv[3], 'w').write('\n'.join(o) + '\n')
